export function getInstantCitySuggestions(query) {
  if (!query) return [];
  const cleanQuery = query.trim().toLowerCase();
  if (cleanQuery.length === 0) return [];

  // Filter cities starting with the query string first, then containing it
  const startsWithMatches = [];
  const containsMatches = [];

  for (const city of ITALIAN_CITIES) {
    const cityNameLower = city.name.toLowerCase();
    if (cityNameLower.startsWith(cleanQuery)) {
      startsWithMatches.push(city);
    } else if (cityNameLower.includes(cleanQuery)) {
      containsMatches.push(city);
    }
  }

  // Combine results with prefix matches first
  const combined = [...startsWithMatches, ...containsMatches];
  
  return combined.slice(0, 8).map(c => ({
    displayName: `${c.name} (${c.region})`,
    cityName: c.name,
    lat: c.lat,
    lon: c.lon,
    isStreet: false
  }));
}
